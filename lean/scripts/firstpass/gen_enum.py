"""Emit the kernel checks of the first pass (KimKimOh/FirstPassChecks/).

Usage: python3 -I gen_enum.py

Inputs, in scripts/firstpass/data/, for h = 3, 9:
  heavy{h}.txt   lines `a t n`: the pairs (a, t) that may hold a block of the region (`needEnum`),
                 with the number n of blocks `enumOK` iterates; written by Heavy.lean.
  left{h}.txt    the blocks (a, b, c) of the region that fail the whole-block test (`blockOKRaw`);
                 written by RegionEval.lean.
Outputs, in KimKimOh/FirstPassChecks/:
  Data{h}.lean          the lists `heavy{h}` and `leftsData{h}`
  Enum{h}_{k}.lean      `enumOK` for each pair (a, t), grouped into files by cost
  Dispatch{h}_{d}.lean  `dispatchRange` for ranges of W values of a
  All{h}.lean           the assemblies `enum{h}_all` and `dispatch{h}`
"""
import os
import re
from collections import defaultdict

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
DATA = os.path.join(ROOT, "scripts/firstpass/data")
OUT = os.path.join(ROOT, "KimKimOh/FirstPassChecks")
HEADER = "-- Generated by scripts/firstpass/gen_enum.py; do not edit."

# P_t = q₁ ⋯ q_t, the products of the primes from 5 (`Pc` in Lean), for t ≤ 8.
PRODUCTS = [1, 5, 35, 385, 5005, 85085, 1616615, 37182145, 1078282205]
# The arguments of `enumOK` for each host: j, s, the profile lists, the mask lists and indices,
# and the worst-step tables at 2 and 3.
HOSTS = {3: ("3", "2", "prof32", "prof33", "mlist32", "mlist33", "pidx32", "pidx33", "wst2_3", "wst3_3"),
         9: ("9", "1", "prof92", "prof93", "mlist92", "mlist93", "pidx92", "pidx93", "wst2_9", "wst3_9")}
BUDGET = 1_200_000   # iterated blocks per file of `enumOK` checks
W = 40               # width of a range of `a` in the dispatcher checks
DISPATCH_PER_FILE = 20
# `amaxT t` for t < 27, as printed by Heavy.lean; it fixes the number of ranges, and the checks
# verify `amaxT t < W K`.
AMAX = {3: [72, 72, 126, 225, 352, 690] + [72] * 21,
        9: [72, 80, 180, 320, 500, 981, 1622] + [72] * 20}


def t_of(delta):
    """The t with P_t ≤ δ < P_{t+1}."""
    t = 0
    while t + 1 < len(PRODUCTS) and PRODUCTS[t + 1] <= delta:
        t += 1
    return t


def read_inputs(h):
    heavy = [tuple(map(int, l.split())) for l in open(f"{DATA}/heavy{h}.txt") if l.strip()]
    nums = list(map(int, re.findall(r"\d+", open(f"{DATA}/left{h}.txt").read())))
    lefts = defaultdict(list)
    for i in range(0, len(nums), 3):
        a, b, c = nums[i:i + 3]
        lefts[(a, t_of(a * c - b * b))].append((b, c))
    for k in lefts:
        assert any((a, t) == k for a, t, _ in heavy), k
    return heavy, lefts


def write_data(h, heavy, lefts):
    by_t = defaultdict(list)
    for a, t, _ in heavy:
        by_t[t].append(a)
    data = [HEADER,
            "import KimKimOh.Compute.Enum", "import KimKimOh.Tables.Data.ProfileData",
            "import KimKimOh.Tables.Data.ChunkData", "", "/-!",
            f"# The pairs `(a, t)` enumerated for K{h} and the blocks left by the whole-block test (generated)",
            "-/", "", "namespace KimKimOh", "", "open Tables", "",
            f"/-- The first norms `a` enumerated for `t`. -/",
            f"def heavy{h} : ℕ → List ℕ"]
    for t in sorted(by_t):
        data.append(f"  | {t} => [{', '.join(map(str, sorted(by_t[t])))}]")
    data += ["  | _ => []", "",
             "set_option maxRecDepth 100000 in",
             f"/-- The blocks `(b, c)` left by the whole-block test, by `(a, t)`. -/",
             f"def leftsData{h} : List ((ℕ × ℕ) × List (ℕ × ℕ)) := ["]
    entries = [f"  (({a}, {t}), [{', '.join(f'({b}, {c})' for b, c in sorted(v))}])"
               for (a, t), v in sorted(lefts.items())]
    data.append(",\n".join(entries))
    data += ["]", "",
             f"/-- The leftover blocks for `(a, t)`. -/",
             f"def leftsOf{h} (a t : ℕ) : List (ℕ × ℕ) := leftsLookup leftsData{h} a t", "",
             "end KimKimOh", ""]
    with open(f"{OUT}/Data{h}.lean", "w") as fh:
        fh.write("\n".join(data))
    return by_t


def write_enum_files(h, heavy):
    """`enumOK` for each pair (a, t), in files of at most BUDGET iterated blocks."""
    args = " ".join(HOSTS[h])
    files, cur, cost = [], [], 0
    for a, t, n in heavy:
        if cur and cost + n > BUDGET:
            files.append(cur)
            cur, cost = [], 0
        cur.append((a, t))
        cost += n
    if cur:
        files.append(cur)
    for k, pairs in enumerate(files):
        lines = [HEADER, f"import KimKimOh.FirstPassChecks.Data{h}", "", "/-!",
                 f"# First-pass enumeration checks for K{h}, part {k} (generated)", "-/", "",
                 "namespace KimKimOh", "", "open Tables", ""]
        for a, t in pairs:
            lines += [f"theorem en{h}_{a}_{t} : enumOK {args} {a} {t} (leftsOf{h} {a} {t}) = true := by",
                      "  decide +kernel", ""]
        lines += ["end KimKimOh", ""]
        with open(f"{OUT}/Enum{h}_{k}.lean", "w") as fh:
            fh.write("\n".join(lines))
    return files


def write_dispatch_files(h):
    """`dispatchRange` for the ranges [W k, W k + W) of a, `DISPATCH_PER_FILE` per file (the
    kernel keeps every value of a declaration, so each range is its own theorem)."""
    args = HOSTS[h]
    nranges = {t: (AMAX[h][t] + W) // W for t in range(27)}
    dfiles, cur = [], []
    for t in range(27):
        for k in range(nranges[t]):
            if len(cur) >= DISPATCH_PER_FILE:
                dfiles.append(cur)
                cur = []
            cur.append((t, k))
    dfiles.append(cur)
    for d, items in enumerate(dfiles):
        disp = [HEADER, "import KimKimOh.Compute.Dispatch", f"import KimKimOh.FirstPassChecks.Data{h}", "",
                "/-!", f"# The dispatcher checks for K{h} by ranges of `a`, part {d} (generated)", "-/", "",
                "namespace KimKimOh", "", "open Tables", ""]
        for t, k in items:
            disp += [f"theorem dispatch{h}_{t}_{k} : dispatchRange {args[0]} {args[1]} {args[2]} {args[3]} heavy{h} {t} {W * k} {W} = true := by",
                     "  decide +kernel", ""]
        disp += ["end KimKimOh", ""]
        with open(f"{OUT}/Dispatch{h}_{d}.lean", "w") as fh:
            fh.write("\n".join(disp))
    return dfiles, nranges


def write_assembly(h, by_t, files, dfiles, nranges):
    """The assemblies: for each t a chain of `And.intro` over the pairs (no `simp`), then case
    analysis on t; and the dispatcher from its ranges."""
    args = HOSTS[h]
    args_s = " ".join(args)
    asm = [HEADER, "import KimKimOh.ListAll", "import KimKimOh.DispatchRanges"]
    asm += [f"import KimKimOh.FirstPassChecks.Dispatch{h}_{d}" for d in range(len(dfiles))]
    asm += [f"import KimKimOh.FirstPassChecks.Enum{h}_{k}" for k in range(len(files))]
    asm += ["", "/-!", f"# All first-pass enumeration checks for K{h} (generated)", "",
            "The whole-block test of Certificate 4.3(a) (`cert:finite`) on the region, and the dispatcher of",
            "Certificate 4.2 (`cert:ranges`).", "-/", "",
            "namespace KimKimOh", "", "open Tables", "", "set_option maxRecDepth 100000", ""]
    for t in range(27):
        names = [f"en{h}_{a}_{t}" for a in sorted(by_t.get(t, []))]
        chain = "trivial"
        for n in reversed(names):
            chain = f"And.intro {n} ({chain})"
        asm += [f"theorem enum{h}_t{t} : ∀ a ∈ heavy{h} {t}, enumOK {args_s} a {t} (leftsOf{h} a {t}) = true :=",
                f"  allP_mem (P := fun a => enumOK {args_s} a {t} (leftsOf{h} a {t}) = true) (l := heavy{h} {t})",
                f"    ({chain})", ""]
    asm += [f"/-- **The first-pass enumeration for K{h}.** -/",
            f"theorem enum{h}_all : ∀ t < 27, ∀ a ∈ heavy{h} t, enumOK {args_s} a t (leftsOf{h} a t) = true := by",
            "  intro t ht", "  interval_cases t",
            f"  exacts [{', '.join(f'enum{h}_t{t}' for t in range(27))}]", ""]
    for t in range(27):
        asm += [f"theorem dispatch{h}_t{t} : dispatchOK {args[0]} {args[1]} {args[2]} {args[3]} heavy{h} {t} = true :=",
                f"  dispatchOK_of_ranges (w := {W}) (K := {nranges[t]}) (by decide +kernel) fun k hk => by",
                "    interval_cases k",
                f"    exacts [{', '.join(f'dispatch{h}_{t}_{k}' for k in range(nranges[t]))}]", ""]
    asm += [f"/-- **The dispatcher for K{h}**: the pairs `(a, t)` of Certificate 4.2 (`cert:ranges`) are enumerated. -/",
            f"theorem dispatch{h} : ∀ t < 27, dispatchOK {args[0]} {args[1]} {args[2]} {args[3]} heavy{h} t = true := by",
            "  intro t ht", "  interval_cases t",
            f"  exacts [{', '.join(f'dispatch{h}_t{t}' for t in range(27))}]", "", "end KimKimOh", ""]
    with open(f"{OUT}/All{h}.lean", "w") as fh:
        fh.write("\n".join(asm))


def main():
    os.makedirs(OUT, exist_ok=True)
    summary = []
    for h in HOSTS:
        heavy, lefts = read_inputs(h)
        by_t = write_data(h, heavy, lefts)
        files = write_enum_files(h, heavy)
        dfiles, nranges = write_dispatch_files(h)
        write_assembly(h, by_t, files, dfiles, nranges)
        summary.append((h, len(heavy), len(files), sum(len(v) for v in lefts.values())))
    print("(host, pairs (a, t), enumeration files, leftover blocks):", summary)


if __name__ == "__main__":
    main()
