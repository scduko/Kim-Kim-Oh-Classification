"""Generate the kernel-checked local witnesses for binary sources (local 2-universality).

Usage: python3 -I gen_local_binary.py > KimKimOh/Local/BinaryData.lean

For a diagonal sublattice `J` of a host at `p = 2` or `3` (`KimKimOh/Local/Diagonal.lean`) and
each residue class of a binary Gram matrix `C = [[a, b], [b, c]]` (modulo `(8, 4, 8)` at 2,
modulo 9 at 3), the table gives either

* a witness: integer matrices `X`, `Y` of size 5 x 2 with `Xᵀ J X ≡ C` (modulo 8 on the diagonal
  and 4 off it at 2, modulo 9 at 3) and `Xᵀ Y ≡ 1 (mod p)`; `lem:local-precision` then gives a
  representation of every `C` in the class over `ℤ_p`; or
* (at 2 only) a direction `u` of an integral superlattice of index 2: `u = (1, 0)` (tag 1),
  `(0, 1)` (tag 2) or `(1, 1)` (tag 3), with `C u ≡ 0 (mod 2)` and `uᵀ C u ≡ 0 (mod 4)`.
  Then `C = Dᵀ C' D` with `det C' = det C / 4`, and the representation follows by induction on
  the determinant.

Matrices are written as lists of ten entries, row-major (entry `(i, j)` at index `2 i + j`).
"""
import itertools
from collections import defaultdict


def indep(x, y, p):
    return any((x[i] * y[j] - x[j] * y[i]) % p for i in range(5) for j in range(i + 1, 5))


def right_inverse(x, y, p):
    """Y (5 x 2) with Xᵀ Y = 1 (mod p), supported on two rows."""
    for r in range(5):
        for s in range(5):
            if r == s:
                continue
            a, b, c, d = x[r], x[s], y[r], y[s]   # A = [[x_r, x_s], [y_r, y_s]]
            det = (a * d - b * c) % p
            if det == 0:
                continue
            inv = pow(det, -1, p)
            # A⁻¹ = inv * [[d, -b], [-c, a]] ; Ŷ = A⁻¹ gives rows r, s of Y
            Yh = [[(inv * d) % p, (-inv * b) % p], [(-inv * c) % p, (inv * a) % p]]
            Y = [[0, 0] for _ in range(5)]
            Y[r] = Yh[0]
            Y[s] = Yh[1]
            # check
            for i, col in enumerate((x, y)):
                for j in range(2):
                    v = sum(col[k] * Y[k][j] for k in range(5)) % p
                    assert v == (1 if i == j else 0)
            return Y
    raise ValueError('dependent columns')


def table(J, p):
    if p == 2:
        R, mods = 4, (8, 4, 8)
        classes = [(a, b, c) for a in range(8) for b in range(4) for c in range(8)]
    else:
        R, mods = 9, (9, 9, 9)
        classes = [(a, b, c) for a in range(9) for b in range(9) for c in range(9)]
    N = lambda v: sum(J[i] * v[i] * v[i] for i in range(5)) % mods[0]
    B = lambda u, v: sum(J[i] * u[i] * v[i] for i in range(5)) % mods[1]
    bynorm = defaultdict(list)
    for v in itertools.product(range(R), repeat=5):
        if any(t % p for t in v):
            bynorm[N(v)].append(v)
    out = []
    for (a, b, c) in classes:
        wit = None
        for x in bynorm[a]:
            for y in bynorm[c]:
                if B(x, y) == b and indep(x, y, p):
                    wit = (x, y)
                    break
            if wit:
                break
        if wit:
            x, y = wit
            Y = right_inverse(x, y, p)
            X = [[x[i], y[i]] for i in range(5)]
            out.append((0, [e for row in X for e in row], [e for row in Y for e in row]))
        else:
            assert p == 2
            if a % 4 == 0 and b % 2 == 0:
                tag = 1
            elif c % 4 == 0 and b % 2 == 0:
                tag = 2
            elif (a + b) % 2 == 0 and (b + c) % 2 == 0 and (a + 2 * b + c) % 4 == 0:
                tag = 3
            else:
                raise ValueError(f'class {(a, b, c)}: no witness and no superlattice')
            out.append((tag, [], []))
    return out


def lean_list(l):
    return '[' + ', '.join(str(v) for v in l) + ']'


def emit(name, doc, tbl, tagged):
    print(f'/-- {doc} -/')
    if tagged:
        print(f'def {name} : List (ℕ × List ℤ × List ℤ) := [')
        print(',\n'.join(f'  ({t}, {lean_list(x)}, {lean_list(y)})' for t, x, y in tbl))
    else:
        print(f'def {name} : List (List ℤ × List ℤ) := [')
        print(',\n'.join(f'  ({lean_list(x)}, {lean_list(y)})' for t, x, y in tbl))
    print(']')
    print()


def main():
    print('-- Generated by scripts/genus/gen_local_binary.py; do not edit.')
    print('import Mathlib.Data.Int.Init')
    print()
    print('/-!')
    print('# Local witnesses for binary sources (generated)')
    print()
    print('See `scripts/genus/gen_local_binary.py` and `KimKimOh/Local/Binary.lean`.')
    print('-/')
    print()
    print('namespace KimKimOh.LocalBinary')
    print()
    emit('w92', 'Binary witnesses for `J92 = ⟨1, 3, 3, 3, 3⟩` (`K₉` at 2), indexed by `32 a + 8 b + c`.',
         table([1, 3, 3, 3, 3], 2), True)
    emit('w93', 'Binary witnesses for `J93 = ⟨1, 1, 2, 3, 6⟩` (`K₉` at 3), indexed by `81 a + 9 b + c`.',
         table([1, 1, 2, 3, 6], 3), False)
    print('end KimKimOh.LocalBinary')


if __name__ == '__main__':
    main()
