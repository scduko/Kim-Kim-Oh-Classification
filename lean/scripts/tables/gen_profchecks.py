"""Emit the kernel checks of the per-chunk profiles and k-steps (KimKimOh/Tables/ProfCheck*.lean
and the assembly ProfChecks.lean).

Usage: python3 -I gen_profchecks.py [OUTDIR]    (default KimKimOh/Tables)

`profChunkOK3` (`profChunkOK2`) checks one chunk: every maximal residue satisfies a profile of the
chunk's mask `pmask` and has the k-steps of the worst-step table `wst` (both from
`gen_chunkdata.py`), against the certified table of `gen_tables.py`. At 3 the 729 chunks are
checked in 27 theorems of 27 chunks, three theorems per file; at 2 the 256 chunks in 8 theorems
of 32 chunks, in one file. `profOK{name}` assembles them.
"""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
SPECS = {"33": (3, 2, "K₃"), "93": (3, 1, "K₉"), "32": (2, 2, "K₃"), "92": (2, 1, "K₉")}  # (p, s, host)
FILES3 = 9  # files per host at 3, each with 3 theorems of 27 chunks
HEADER = "-- Generated by scripts/tables/gen_profchecks.py; do not edit."


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "KimKimOh/Tables")
    imports, body = set(), []
    for name, (p, s, host) in SPECS.items():
        if p == 3:
            groups, m, chk, mod = 27, 27, "profChunkOK3", "Profiles3"    # groups theorems of m chunks
            files = [(f"ProfCheck{name}_{f}", list(range(3 * f, 3 * f + 3))) for f in range(FILES3)]
        else:
            groups, m, chk, mod = 8, 32, "profChunkOK2", "Profiles2"
            files = [(f"ProfCheck{name}", list(range(8)))]
        call = f"{chk} acc{name} {s} prof{name} pmask{name} wst{p}_{name[0]}"
        for fname, ks in files:
            lines = [HEADER, f"import KimKimOh.Tables.{mod}", "import KimKimOh.Tables.Data.ProfileData",
                     "import KimKimOh.Tables.Data.ChunkData",
                     f"import KimKimOh.Tables.Data.T{name}", "", "/-!",
                     f"# The kernel check of the profiles and k-steps of {host} at {p} (generated)", "-/", "",
                     "namespace KimKimOh.Tables", ""]
            for k in ks:
                lines += [f"theorem pc{name}_{k} : ∀ i < {m}, {call} ({m} * {k} + i) = true := by",
                          "  decide +kernel", ""]
            lines += ["end KimKimOh.Tables", ""]
            with open(f"{out}/{fname}.lean", "w") as fh:
                fh.write("\n".join(lines))
            imports.add(f"import KimKimOh.Tables.{fname}")
        body += ["", f"/-- Every chunk passes the profile check of {host} at {p}. -/",
                 f"theorem profOK{name} : ∀ blk < {groups * m}, {call} blk = true := by",
                 "  intro blk hb",
                 f"  have h : ∀ k < {groups}, ∀ i < {m}, {call} ({m} * k + i) = true := by",
                 "    intro k hk", "    interval_cases k"]
        body += [f"    · exact pc{name}_{k}" for k in range(groups)]
        body += [f"  have := h (blk / {m}) (by omega) (blk % {m}) (Nat.mod_lt _ (by norm_num))",
                 "  rwa [Nat.div_add_mod] at this"]
    local = ([HEADER] + sorted(imports)
             + ["", "/-!", "# The chunk checks of both hosts at 2 and 3", "-/", "", "namespace KimKimOh.Tables"]
             + body + ["", "end KimKimOh.Tables", ""])
    with open(f"{out}/ProfChecks.lean", "w") as fh:
        fh.write("\n".join(local))
    print("ok")


if __name__ == "__main__":
    main()
