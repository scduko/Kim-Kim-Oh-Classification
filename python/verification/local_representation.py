"""Appendix A.1, Table 3: construct ℛ_{j,p} and identify maximal Gram residues."""
from functools import cache
from itertools import product
from math import prod

# The entries are the diagonal coefficients in a local orthogonal basis.
HOST_DIAGONALS = {
    (3,2): (1,1,3,3,3),
    (9,2): (1,3,3,3,3),
    (3,3): (1,1,1,2,6),
    (9,3): (1,1,2,3,6),
}
BYTE_BITS = tuple(bytes((b >> i) & 1 for i in range(8)) for b in range(256))


def determinant(g):
    a,b,c,d,e,f = g
    return (a*c-b*b)*f-c*d*d+2*b*d*e-a*e*e


class Residues:
    """Encode the symmetric Gram matrix with rows (a,b,d), (b,c,e), (d,e,f).

    The tuple (a,b,c,d,e,f) puts the leading block first, followed by the
    last column. Here d and e denote the paper's r1 and r2.
    """
    def __init__(self, p):
        self.q,self.r = (8,4) if p == 2 else (9,9)
        q,r = self.q,self.r
        self.moduli = (q,r,q,r,r,q)
        self.size = prod(self.moduli)

    def encode(self, a,b,c,d,e,f):
        q,r = self.q,self.r
        return (((((a*r+b)*q+c)*r+d)*r+e)*q+f)

    def decode(self, code):
        q,r = self.q,self.r
        code,f = divmod(code,q)
        code,e = divmod(code,r)
        code,d = divmod(code,r)
        code,c = divmod(code,q)
        a,b = divmod(code,r)
        return a,b,c,d,e,f


@cache
def residues(p):
    return Residues(p)


def pack(flags):
    """One bit per Gram residue in its mixed-radix enumeration."""
    packed = bytearray((len(flags)+7)//8)
    for i,value in enumerate(flags):
        if value:
            packed[i//8] |= 1 << (i%8)
    return int.from_bytes(packed,"little")


def unpack(bits, size):
    raw = bits.to_bytes((size+7)//8,"little")
    return b"".join(BYTE_BITS[b] for b in raw)[:size]


@cache
def lower_mask(size, radix, stride, shift):
    """Indices whose chosen digit can increase by shift without wrapping."""
    width = radix*stride
    first = (1 << ((radix-shift)*stride))-1
    return first * (((1 << size)-1)//((1 << width)-1))


def translated(bits, moduli, shift):
    """Translate every tuple in a packed subset by adding shift entrywise."""
    stride = size = prod(moduli)
    for modulus,offset in zip(moduli,shift):
        stride //= modulus
        h = offset % modulus
        if h:
            mask = lower_mask(size,modulus,stride,h)
            bits = ((bits & mask) << (stride*h)) | ((bits & ~mask) >> (stride*(modulus-h)))
    return bits


@cache
def extend(subspace, v, p):
    if v in subspace:
        return subspace
    return frozenset(tuple((x+t*y)%p for x,y in zip(a,v))
                     for a in subspace for t in range(p))


@cache
def row_contributions(d, p):
    """The contributions d vvᵀ and the directions of the rows modulo p."""
    q,r = residues(p).q,residues(p).r
    period = 4 if p == 2 else (3 if d%3 == 0 else 9)
    contributions = set()
    for i,j,k in product(range(period),repeat=3):
        v = (i%p,j%p,k%p)
        v = min(v,tuple(-t%p for t in v))  # both signs span the same subspace
        gram = (d*i*i%q,d*i*j%r,d*j*j%q,d*i*k%r,d*j*k%r,d*k*k%q)
        contributions.add((v,gram))
    return contributions


@cache
def acceptance_table(host, p):
    """Mark precisely the Gram residues obtained from rows spanning F_p^3."""
    space = residues(p)
    zero = frozenset(((0,0,0),))
    totals = {zero: 1}  # bit zero represents the all-zero Gram tuple
    # After each diagonal coefficient, totals[span] records all partial
    # Gram sums whose chosen rows span exactly this subspace modulo p.
    for i,d in enumerate(HOST_DIAGONALS[host,p]):
        updated = {}
        rows_left = 4-i
        for span,sums in totals.items():
            for v,gram in row_contributions(d,p):
                enlarged = extend(span,v,p)
                # Each remaining row can increase the span dimension by at most one.
                if len(enlarged)*p**rows_left < p**3:
                    continue
                contributions = translated(sums,space.moduli,gram)
                updated[enlarged] = updated.get(enlarged,0) | contributions
        totals = updated
    full = frozenset(product(range(p),repeat=3))
    return unpack(totals[full],space.size)


def represents(host,p,g):
    space = residues(p)
    code = space.encode(*(t%m for t,m in zip(g,space.moduli)))
    return bool(acceptance_table(host,p)[code])


@cache
def radical_lines(p, residue):
    a,b,c,d,e,f = residue
    return tuple((x,y,z) for x,y,z in product(range(p),repeat=3)
                 if next((t for t in (x,y,z) if t),0)==1
                 and (a*x+b*y+d*z)%p==0
                 and (b*x+c*y+e*z)%p==0
                 and (d*x+e*y+f*z)%p==0)


def maximal_at(p,g):
    """Every possible index-p enlargement is generated by a radical line."""
    a,b,c,d,e,f = g
    lines = radical_lines(p,tuple(t%p for t in g))
    return all((a*x*x+c*y*y+f*z*z+2*(b*x*y+d*x*z+e*y*z))%(p*p)
               for x,y,z in lines)


@cache
def source_flags(p):
    space = residues(p)
    grams = product(*(range(m) for m in space.moduli))
    if p == 2:
        return bytes(determinant(g)%4 != 0 for g in grams)
    return bytes(maximal_at(p,g) for g in grams)


def main():
    for p in (2,3):
        space = residues(p)
        maximal = source_flags(p)
        print(f"At {p}: {space.size} Gram residues, {sum(maximal)} maximal.")
        for host in (3,9):
            marks = acceptance_table(host,p)
            expected = {(3,2): 28420, (9,2): 22624, (3,3): 451386, (9,3): 355485}
            if sum(marks) != expected[host,p]:
                raise ArithmeticError(("Table 3 representation count", host, p))
            print(f"K{host}: {sum(marks)} residues with a primitive representation at {p}.")


if __name__ == "__main__":
    main()
