"""Generate the data and kernel checks of the last-column test and the terminal enumeration.

Usage: python3 -I gen_terminal.py ARCHIVE [--no-tables]

ARCHIVE is the directory containing the manuscript’s Python certificates and checker. The script imports
the supplement's checker (`audit/check_coverage.py`) and reads the records `audit/coverage.json.gz`
(the surviving classes and `U(B)` of each block, a copy of
`certificates/last_column_bounds.json.gz`) and `audit/witnesses.jsonl.gz` (a covector for each
enumerated matrix, a copy of `certificates/representation_witnesses.jsonl.gz`). It stops if a
witness key occurs twice or if a witness is not used. The blocks left by the
first pass are read from `KimKimOh/FirstPassChecks/Data{3,9}.lean` (written by
`scripts/firstpass/gen_enum.py`). Outputs:

  KimKimOh/Tables/Data/TermTables.lean   the tables r2 (4 ∤ D at 2), mx, mw (maximal at 3)
  KimKimOh/Terminal/TabCheck.lean        their kernel checks
  KimKimOh/Terminal/Blocks{h}.lean       the list of blocks and the sizes of its batches
  KimKimOh/Terminal/Batches{h}_{i}.lean  the certificates of a few batches and their checks
  KimKimOh/Terminal/All{h}.lean          the assembly `termAll{h}`

With --no-tables only the last three are written.

The certificate of a block is a Lean `TermCert` with three fields.

* `U`: the bound `U(B)` of the record (0 if no class survives).
* `opts`: the pairs `(x, y)` needed to reproduce the record's bounds, chosen greedily from all
  pairs with `B' > 0` (`options`, `choose`). Each is packed as by `decOpt`:
    bits 0–3 x, 4–7 |y|, 8 [y < 0], 9–16 the window g, 17–20 the number of factor entries,
    then 40 bits per entry from bit 21: q (16 bits), kind (2 bits), w (16 bits).
  An entry of kind 0 is a prime q ≥ 5 dividing Δ that is kept in the sieve; w = ⌊√q⌋ - 1 lets the
  kernel check primality by trial division. An entry of kind 1 or 2 is a prime q at which the
  diagonal entry a - s x² or c - s y² of B' is j w² modulo q, so that q is omitted.
* `wits`: one 64-bit word per enumerated matrix, in the order of `liftsOf`, packed as by `decW`:
    bits 0–8 λ + 2 (3 bits per coordinate), 9–15 and 16–22 the overlattice codes at 2 and 3,
    then two square-class entries (q, i, w) of 12 bits (5, 2, 5) from bit 23.
  An overlattice code is 0 for none, else 1 + k + 3 (9 z₀ + 3 z₁ + z₂) for the vector z with first
  nonzero entry z_k = 1. A square-class entry says that the diagonal entry i of C is j w² modulo
  q, for each prime q ≥ 5 dividing every 2×2 minor of C.

The checks are grouped into batches by an estimate of their kernel cost, and the batches into
files; a heavy batch gets a file of its own, and these files import each other in a chain so that
lake builds them one at a time.
"""
