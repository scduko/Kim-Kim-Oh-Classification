"""Per-chunk profile masks and worst-step tables (KimKimOh/Tables/Data/ChunkData.lean).

Usage: python3 -I gen_chunkdata.py ARCHIVE [OUTDIR]    (default KimKimOh/Tables/Data)

ARCHIVE is the manuscript's verification archive; its `verification/` modules give the residues,
the maximality flags, the acceptance tables and the profiles. Outputs, for each host and prime:

* `pmask{host}{p}`: for each chunk, the bitmask of the profiles (indices into `prof{host}{p}` of
  its class) satisfied by its maximal residues; 16 bits per chunk. `mlist{host}{p}` lists the
  distinct masks of each class of `a`, and `pidx{host}{p}` gives the index of each chunk's mask in
  that list (4 bits per chunk), which the bounds `hiTab` use.
* `wst2_{host}`: for each chunk at 2 and (x, y) mod 4, the worst step of k (k mod 4, x and y fixed
  mod 4) over the maximal residues of the chunk: 1, 2, 4, or 15 (none); 4 bits each, 64 per chunk.
* `wst3_{host}`: for each chunk at 3 and (x, y) mod 3, the worst step of k (directions mod 3 with
  all lifts mod 9, `𝒰_{j,3}`): 1, 3 or 15; 4 bits each, 64 per chunk.

The kernel checks these data against the certified tables (`gen_profchecks.py`).
"""
import os
import sys
from itertools import product

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
SCALES = {3: 2, 9: 1}


def chunk_masks(host, p):
    """For each chunk, the bitmask of the profiles of its maximal residues."""
    space = residues(p)
    profs = local_profiles(host, p)
    idx = [{P: i for i, P in enumerate(sorted(profs[cls]))} for cls in range(len(profs))]
    accepted = permissible(host, p)
    columns = [accepted[z] for z in product(range(p), repeat=3)]
    nchunk = 256 if p == 2 else 729
    per = [0] * nchunk
    stride = space.size // nchunk
    ncls = 4 if p == 2 else 3
    for code, (maximal, *flags) in enumerate(zip(source_flags(p), *columns)):
        if maximal:
            options = tuple(steps(p, tuple(flags[x * p * p:(x + 1) * p * p])) for x in range(p))
            a = space.decode(code)[0]
            per[code // stride] |= 1 << idx[a % ncls][options]
    return per


def wst2(host):
    """The worst step of k at 2, as in `stepSet2`: 1 if every k mod 4 is accepted, 2 if both k of
    one parity are, 4 if some k is, 15 if none."""
    s = SCALES[host]
    space, acc, flags = residues(2), acceptance_table(host, 2), source_flags(2)
    tab = 0
    for a, b, c in product(range(8), range(4), range(8)):
        blk = 32 * a + 8 * b + c
        for x, y in product(range(4), range(4)):
            w = 1
            for d, e, f in product(range(4), range(4), range(8)):
                code = space.encode(a, b, c, d, e, f)
                if not flags[code]:
                    continue
                ok = [acc[space.encode((a - s * x * x) % 8, (b - s * x * y) % 4, (c - s * y * y) % 8,
                                       (d - s * x * k) % 4, (e - s * y * k) % 4, (f - s * k * k) % 8)]
                      for k in range(4)]
                if all(ok):
                    st = 1
                elif (ok[0] and ok[2]) or (ok[1] and ok[3]):
                    st = 2
                elif any(ok):
                    st = 4
                else:
                    st = 15
                w = max(w, st)
            tab |= w << (64 * blk + 4 * (4 * x + y))
    return tab


def wst3(host):
    """The worst step of k at 3, as in `stepSet3`: 1 if every k mod 3 is permissible, 3 if some
    k is, 15 if none."""
    space, perm, flags = residues(3), permissible(host, 3), source_flags(3)
    tab = 0
    for a, b, c in product(range(9), repeat=3):
        blk = 81 * a + 9 * b + c
        for x, y in product(range(3), range(3)):
            w = 1
            for d, e, f in product(range(9), repeat=3):
                code = space.encode(a, b, c, d, e, f)
                if not flags[code]:
                    continue
                ok = [perm[(x, y, k)][code] for k in range(3)]
                st = 1 if all(ok) else (3 if any(ok) else 15)
                w = max(w, st)
            tab |= w << (64 * blk + 4 * (3 * x + y))
    return tab


def packed(vals, bits):
    return sum(v << (bits * i) for i, v in enumerate(vals))


def main():
    # The archive's modules, bound as globals for the functions above.
    global residues, source_flags, acceptance_table, permissible, steps, local_profiles
    if len(sys.argv) not in (2, 3):
        raise SystemExit(__doc__)
    sys.path.insert(0, os.path.join(os.path.abspath(sys.argv[1]), "verification"))
    from local_representation import residues, source_flags, acceptance_table
    from residue_census import permissible, steps, local_profiles
    out = sys.argv[2] if len(sys.argv) == 3 else os.path.join(ROOT, "KimKimOh/Tables/Data")
    lines = ["-- Generated by scripts/tables/gen_chunkdata.py; do not edit.", "import KimKimOh.Tables.Bits", "",
             "/-!", "# Per-chunk profile masks and worst-step tables (generated)", "-/", "",
             "namespace KimKimOh.Tables", ""]
    for host in (3, 9):
        for p in (2, 3):
            m = chunk_masks(host, p)
            lines += [f"/-- The profiles of each chunk of K{host} at {p}, as bitmasks (16 bits per chunk). -/",
                      f"def pmask{host}{p} : ℕ := 0x{packed(m, 16):x}", ""]
            # distinct masks by class, and the index of each chunk's mask in its class list
            ncls = 4 if p == 2 else 3
            stride = 32 if p == 2 else 81  # chunk = stride * a + ...
            dist = [sorted({m[blk] for blk in range(len(m)) if (blk // stride) % ncls == cls}) for cls in range(ncls)]
            idx = [dist[(blk // stride) % ncls].index(m[blk]) for blk in range(len(m))]
            assert max(len(d) for d in dist) <= 16
            body = [f"  | {cls} => [{', '.join(str(v) for v in dist[cls])}]" for cls in range(ncls)]
            lines += [f"/-- The distinct chunk masks of K{host} at {p}, by class. -/",
                      f"def mlist{host}{p} : ℕ → List ℕ"] + body + ["  | _ => []", "",
                      f"/-- The index of each chunk's mask in its class list (4 bits per chunk). -/",
                      f"def pidx{host}{p} : ℕ := 0x{packed(idx, 4):x}", ""]
        lines += [f"/-- The worst steps of k at 2 for K{host}, by chunk and (x, y) mod 4. -/",
                  f"def wst2_{host} : ℕ := 0x{wst2(host):x}", "",
                  f"/-- The worst steps of k at 3 for K{host}, by chunk and (x, y) mod 3. -/",
                  f"def wst3_{host} : ℕ := 0x{wst3(host):x}", ""]
    lines += ["end KimKimOh.Tables", ""]
    with open(os.path.join(out, "ChunkData.lean"), "w") as fh:
        fh.write("\n".join(lines))
    print("ok")


if __name__ == "__main__":
    main()
