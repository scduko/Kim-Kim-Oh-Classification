def certificates(H, groups, recs, wits, used):
    """The certificate of each block left by the first pass, with its estimated kernel cost:
    a list of (cost, (U, options, witnesses), (a, b, c))."""
    blocks = []
    for (a, t), bcs in groups:
        for b, c in bcs:
            U, surv, opts = choose(H['target'], a, b, c, recs.get((H['target'], a, b, c)))
            pts, iters = lifts(a, b, c, U, surv) if surv else ([], 0)
            W = []
            for pt in pts:
                key = (H['target'], a, b, c) + pt
                W.append(witness(H['j'], H['s'], a, b, c, pt, wits[key]))
                used.add(key)
            cost = 30 + 60 * len(opts) + iters + 40 * len(W)
            blocks.append((cost, (U, opts, W), (a, b, c)))
    return blocks


def batches_by_cost(blocks):
    """Consecutive blocks grouped into batches of cost at most BATCH_COST (or one block)."""
    batches, costs, cur, cost = [], [], [], 0
    for cst, cert, abc in blocks:
        if cur and cost + cst > BATCH_COST:
            batches.append(cur)
            costs.append(cost)
            cur, cost = [], 0
        cur.append((cert, abc))
        cost += cst
    batches.append(cur)
    costs.append(cost)
    return batches, costs


def files_by_cost(costs):
    """Consecutive batches grouped into files of cost at most FILE_COST; a batch above HEAVY_COST
    gets a file of its own."""
    files, cur, cost = [], [], 0
    for ci, cst in enumerate(costs):
        if cst > HEAVY_COST:
            files.append([ci])
            continue
        if cur and cost + cst > FILE_COST:
            files.append(cur)
            cur, cost = [], 0
        cur.append(ci)
        cost += cst
    if cur:
        files.append(cur)
    return files


