"""Emit the kernel checks of the certified local tables (KimKimOh/Tables/Check*.lean).

Usage: python3 -I gen_checks.py [OUTDIR]        (default KimKimOh/Tables)

`accChunkOK3` (`accChunkOK2`) checks one chunk of the table of `gen_tables.py`: its witnesses and
the orbits that cover it. The 729 chunks at 3 are checked in 27 theorems of 27 chunks each (the
kernel keeps every value of a declaration in memory, so one theorem per host would be too large),
the 256 chunks at 2 in one theorem; `accOK{name}` assembles them.
"""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
SPECS = {  # name: (p, diagonal of J, host)
    "33": (3, [1, 1, 1, 2, 6], "K₃"), "93": (3, [1, 1, 2, 3, 6], "K₉"),
    "32": (2, [1, 1, 3, 3, 3], "K₃"), "92": (2, [1, 3, 3, 3, 3], "K₉"),
}


def check_file(name, p, J, host):
    if p == 3:
        n, m, chk, acc = 27, 27, "accChunkOK3", "Accept3"     # n theorems of m chunks
    else:
        n, m, chk, acc = 1, 256, "accChunkOK2", "Accept2"
    lines = [f"-- Generated by scripts/tables/gen_checks.py; do not edit.",
             f"import KimKimOh.Tables.{acc}", f"import KimKimOh.Tables.Data.T{name}", "",
             "/-!", f"# The kernel check of the local table of {host} at {p} (generated)", "-/", "",
             "namespace KimKimOh.Tables", "",
             f"/-- The diagonal of `J` for {host} at {p}. -/",
             f"def J{name}f (r : ℕ) : ℕ := {J}.getD r 0", ""]
    for k in range(n):
        lines += [f"theorem ck{name}_{k} : ∀ i < {m}, {chk} J{name}f acc{name} wit{name} ({m} * {k} + i) = true := by",
                  "  decide +kernel", ""]
    lines += [f"/-- Every chunk of the table of {host} at {p} passes. -/",
              f"theorem accOK{name} : ∀ blk < {n * m}, {chk} J{name}f acc{name} wit{name} blk = true := by",
              "  intro blk hb",
              f"  have h : ∀ k < {n}, ∀ i < {m}, {chk} J{name}f acc{name} wit{name} ({m} * k + i) = true := by",
              "    intro k hk",
              "    interval_cases k"]
    for k in range(n):
        lines.append(f"    · exact ck{name}_{k}")
    lines += [f"  have := h (blk / {m}) (by omega) (blk % {m}) (Nat.mod_lt _ (by norm_num))",
              f"  rwa [Nat.div_add_mod] at this", "", "end KimKimOh.Tables", ""]
    return "\n".join(lines)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "KimKimOh/Tables")
    for name, (p, J, host) in SPECS.items():
        with open(f"{out}/Check{name}.lean", "w") as fh:
            fh.write(check_file(name, p, J, host))
    print("ok")


if __name__ == "__main__":
    main()
