"""Generate the profile lists (KimKimOh/Tables/Data/ProfileData.lean).

Usage: python3 -I gen_profiles.py ARCHIVE [OUTDIR]     (default KimKimOh/Tables/Data)

ARCHIVE is the manuscript's verification archive; its `verification/residue_census.py` computes
the profiles of `app:prescriptions`. `prof{host}{p} cls` lists the distinct profiles of the
maximal residues whose first entry is `cls` modulo 4 (p = 2) or 3 (p = 3). The data need not be
trusted: the kernel checks every chunk against the certified tables (`gen_profchecks.py`).
"""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))


def lean_profile(P):
    """A profile: for each x mod p, its list of step pairs (h, d)."""
    return "[" + ", ".join("[" + ", ".join(f"({h}, {d})" for h, d in opts) + "]" for opts in P) + "]"


def main():
    if len(sys.argv) not in (2, 3):
        raise SystemExit(__doc__)
    sys.path.insert(0, os.path.join(os.path.abspath(sys.argv[1]), "verification"))
    from residue_census import local_profiles
    out = sys.argv[2] if len(sys.argv) == 3 else os.path.join(ROOT, "KimKimOh/Tables/Data")
    lines = ["-- Generated by scripts/tables/gen_profiles.py; do not edit.",
             "import KimKimOh.Tables.Bits", "", "/-!", "# Profiles of the maximal residues (generated)", "-/", "",
             "namespace KimKimOh.Tables", ""]
    for host in (3, 9):
        for p in (2, 3):
            prof = local_profiles(host, p)
            ncls = 4 if p == 2 else 3
            body = ["  | " + str(cls) + " => [" + ", ".join(lean_profile(P) for P in sorted(prof[cls])) + "]"
                    for cls in range(ncls)]
            lines += [f"/-- The profiles at {p} of the maximal residues for K{host}, by the class of `a`. -/",
                      f"def prof{host}{p} : ℕ → List (List (List (ℕ × ℕ)))"] + body + ["  | _ => []", ""]
    lines += ["end KimKimOh.Tables", ""]
    with open(os.path.join(out, "ProfileData.lean"), "w") as fh:
        fh.write("\n".join(lines))
    print("ok")


if __name__ == "__main__":
    main()
